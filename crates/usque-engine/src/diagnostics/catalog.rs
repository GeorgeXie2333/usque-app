fn check(
    id: &'static str,
    category: Category,
    dependencies: &'static [&'static str],
    minimum_mode: Mode,
    resource_group: &'static str,
    kind: Kind,
) -> Arc<dyn DiagnosticCheck> {
    Arc::new(PassiveCheck::new(
        id,
        category,
        dependencies,
        minimum_mode,
        resource_group,
        kind,
    ))
}
